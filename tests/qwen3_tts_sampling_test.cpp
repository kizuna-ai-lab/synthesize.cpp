int main() {
    // Hugging Face's rule: a positive logit is divided and a negative one
    // multiplied, so both move toward zero. Rewarding a negative score for
    // having appeared would be the opposite of a penalty.
    {
        std::vector<float>         logits  = { 2.0f, -2.0f, 0.5f, -0.5f };
        const std::vector<int32_t> history = { 0, 1 };
        synth::qwen3tts::apply_repetition_penalty(logits, history, 2.0f);
        SYNTH_TEST_CHECK(std::fabs(logits[0] - 1.0f) < 1e-6f);
        SYNTH_TEST_CHECK(std::fabs(logits[1] + 4.0f) < 1e-6f);
        // Untouched entries keep their value exactly.
        SYNTH_TEST_CHECK(logits[2] == 0.5f && logits[3] == -0.5f);
    }

    // A code drawn many times is penalised once, not once per occurrence.
    // Compounding would make the penalty a function of repetition count, and the
    // reference processor walks the sequence dividing a fresh copy of the logits.
    {
        std::vector<float> once   = { 4.0f };
        std::vector<float> thrice = { 4.0f };
        synth::qwen3tts::apply_repetition_penalty(once, { 0 }, 2.0f);
        synth::qwen3tts::apply_repetition_penalty(thrice, { 0, 0, 0 }, 2.0f);
        SYNTH_TEST_CHECK(once[0] == thrice[0]);
        SYNTH_TEST_CHECK(std::fabs(once[0] - 2.0f) < 1e-6f);
    }

    // A penalty of one is the identity, which is what a package declaring no
    // penalty must produce -- not a silently different distribution.
    {
        std::vector<float> logits = { 1.5f, -3.0f, 0.0f };
        synth::qwen3tts::apply_repetition_penalty(logits, { 0, 1, 2 }, 1.0f);
        SYNTH_TEST_CHECK(logits[0] == 1.5f && logits[1] == -3.0f && logits[2] == 0.0f);
    }

    // An empty history leaves everything alone: the first frame of an utterance
    // has nothing to suppress.
    {
        std::vector<float> logits = { 1.0f, 2.0f };
        synth::qwen3tts::apply_repetition_penalty(logits, {}, 1.05f);
        SYNTH_TEST_CHECK(logits[0] == 1.0f && logits[1] == 2.0f);
    }

    // Out-of-range codes are ignored rather than read. A history entry can only
    // be malformed if something upstream is wrong, and reading past the logits
    // would turn that into memory corruption.
    {
        std::vector<float> logits = { 1.0f, 2.0f };
        synth::qwen3tts::apply_repetition_penalty(logits, { -1, 2, 99 }, 2.0f);
        SYNTH_TEST_CHECK(logits[0] == 1.0f && logits[1] == 2.0f);
    }

    // The whole filter chain against the reference's own logits processors, on
    // identical logits. This is the check that would have caught the missing
    // repetition penalty the day it was written.
    //
    // Both sides are fed the same numbers, so sampling, dtype and accumulated
    // graph error are all out of the comparison and only the chain remains. The
    // parameters come from the checkpoint's generation config, captured by the
    // dump script rather than repeated here -- a fixture built from hardcoded
    // values would reproduce the mistake instead of catching it.
    //
    // Compared as probabilities. A rejected entry is -inf on one side and simply
    // unreachable on the other, and what decides a draw is the distribution.
    {
        synth::qwen3tts::SamplingParams params;
        params.enabled     = true;
        params.temperature = kTemperature;
        params.top_k       = kTopK;
        params.top_p       = kTopP;

        size_t history_offset = 0;
        for (uint32_t step = 0; step < kSteps; ++step) {
            std::vector<float> logits(kLogits + size_t(step) * kVocab, kLogits + size_t(step + 1) * kVocab);

            std::vector<int32_t> history(kHistory + history_offset,
                                         kHistory + history_offset + size_t(kHistoryLengths[step]));
            history_offset += size_t(kHistoryLengths[step]);

            synth::qwen3tts::apply_repetition_penalty(logits, history, kRepetitionPenalty);
            const synth::qwen3tts::SamplingDistribution ours = synth::qwen3tts::sampling_distribution(logits, params);

            // The reference's processed scores, turned into the same
            // distribution: softmax over what it left finite.
            const float * expected = kExpectedScores + size_t(step) * kVocab;
            double        total    = 0.0;
            double        highest  = -std::numeric_limits<double>::infinity();
            for (uint32_t code = 0; code < kVocab; ++code) {
                if (expected[code] > highest) {
                    highest = expected[code];
                }
            }
            std::vector<double> reference(kVocab, 0.0);
            for (uint32_t code = 0; code < kVocab; ++code) {
                if (expected[code] > -std::numeric_limits<float>::infinity()) {
                    reference[code] = std::exp(double(expected[code]) - highest);
                    total += reference[code];
                }
            }
            SYNTH_TEST_CHECK(total > 0.0);
            for (uint32_t code = 0; code < kVocab; ++code) {
                reference[code] /= total;
                const double mine = ours.probability(code);
                SYNTH_TEST_CHECK(std::fabs(mine - reference[code]) < 1e-6);
            }
        }
    }

    return 0;
}
